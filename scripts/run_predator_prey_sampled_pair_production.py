            if source == "true":
                prey = arrays["true_prey"][0, time_index]
                predator = arrays["true_predator"][0, time_index, 0]
            else:
                prey = arrays[f"{source}_prey"][0, time_index]
                predator = arrays[f"{source}_predator"][0, time_index, 0]
            axis.scatter(prey[:, 0], prey[:, 1], s=4, alpha=0.65, linewidths=0)

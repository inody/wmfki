def validate_production(requested):
    if requested.get("task") != "predator_prey_sampled_pair_production_P50":
        raise ValueError("wrong P50 production task")
    if requested.get("protocol_version") != 1:
        raise ValueError("unsupported P50 production protocol version")
    if requested.get("study_status") != "scientific_candidate_P50_matched_R20":
        raise ValueError("wrong P50 production status")
    study = requested.get("study", {})
    if study.get("repetitions") != 20 or study.get("repetition_indices") != list(range(20)):
        raise ValueError("all twenty predeclared repetitions are required")
    if study.get("pair_ratios") != [50] or study.get("run_all_sweep_conditions") is not True:
        raise ValueError("production ratio or condition grid changed")
    if study.get("representative_trajectory_repetition") != 0:
        raise ValueError("representative trajectory repetition changed")
    pair = requested.get("pair_sampling", {})
    required = {
        "quadratic_block": "prey_prey_only",
        "ordered": True,
        "exclude_diagonal": True,
        "with_replacement": True,
        "time_policy": "independent_at_each_observation_time",
        "ratio_coupling": "single_production_ratio_P_over_N_50",
        "condition_coupling": "same_split_seed_and_physical_time_share_pair_draws_when_particle_count_matches",
        "index_sharing": "one_index_set_shared_by_all_spatial_tests_temporal_tests_and_dictionary_atoms_at_a_trajectory_time",
        "cross_species_policy": "prey_predator_and_predator_prey_sums_exact",
        "training_validation_policy": "independent_pair_samples",
        "lambda_selection": "sampled_validation_weak_residual_mse",
        "base_seed": 932000,
        "training_offset": 0,
        "validation_offset": 1000000,
        "repetition_stride": 1013,
    }
    if pair != required:
        raise ValueError("P50 pair-sampling policy changed")
    if requested.get("output_policy") != {
        "exclusive_new_directory": True,
        "modify_existing_results": False,
        "modify_confirmation_output": False,
        "modify_R5_output": False,
        "modify_manuscript": False,
        "modify_current_figures": False,
    }:
        raise ValueError("P50 output protection policy changed")
    pinned = {
        ROOT / requested["base_config"]: requested["base_config_sha256"],
        ROOT / requested["reference_frozen_run"] / "manifest.json": requested["reference_manifest_sha256"],
        ROOT / requested["reference_frozen_run"] / "records.json": requested["reference_records_sha256"],
        ROOT / requested["reference_frozen_run"] / "requested_protocol.json": requested["reference_requested_protocol_sha256"],
    }
    if requested.get("source_mode") != "fresh_full_pair_stage_outputs":
        pinned.update({
            ROOT / requested["source_confirmation_run"] / "manifest.json": requested["source_confirmation_manifest_sha256"],
            ROOT / requested["source_confirmation_run"] / "records.json": requested["source_confirmation_records_sha256"],
            ROOT / requested["source_confirmation_run"] / "confirmation_report.json": requested["source_confirmation_report_sha256"],
            ROOT / requested["source_confirmation_run"] / "verification" / "verification.json": requested["source_confirmation_verification_sha256"],
        })
    for path, expected in pinned.items():
        if not path.is_file() or digest(path) != expected:
            raise ValueError(f"pinned production input changed: {path}")



def table_metrics(output, records, reference, application_summary, trajectory):
    condition_id = "observation_noise-04"
    nominal = [row for row in records if row["condition"]["id"] == condition_id]
    full = [row for row in reference if row["condition"]["id"] == condition_id]
    rows = []
    for method in ("lasso", "ols"):
        for source_name, source_rows in (("full_pair", full), ("P50", nominal)):
            drift = finite_summary([
                row["methods"][method]["held_out_drift"]["species_balanced_relative"]
                for row in source_rows
            ])
            rows.append({"source": source_name, "method": method, "channel": "all", "metric": "nominal_species_balanced_drift", **drift})
            for channel in runner.CHANNEL_NAMES:
                for metric in ("coefficient_error_relative", "profile_error_relative"):
                    summary = finite_summary([
                        row["methods"][method]["channels"][channel][metric]
                        for row in source_rows
                    ])
                    rows.append({"source": source_name, "method": method, "channel": channel, "metric": metric, **summary})
    for source in ("full_pair", "P50"):
        for method in ("lasso", "ols"):
            item = trajectory["methods"][source][method]
            rows.append({
                "source": source, "method": method, "channel": "all",
                "metric": "representative_trajectory_species_balanced_relative",
                "count": 1, "mean": item.get("species_balanced_relative"),
                "rmse": item.get("species_balanced_relative"),
                "median": item.get("species_balanced_relative"),
                "q25": item.get("species_balanced_relative"),
                "q75": item.get("species_balanced_relative"),
            })
    write_json(output / "table_metrics.json", rows)
    with (output / "table_metrics.csv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    lines = [
        "# Predator--prey P=50N table metrics", "",
        "| source | method | channel | metric | mean | RMSE | median |",
        "|---|---|---|---|---:|---:|---:|",
    ]
    for row in rows:
        lines.append(
            f"| {row['source']} | {row['method']} | {row['channel']} | {row['metric']} | {row['mean']:.6g} | {row['rmse']:.6g} | {row['median']:.6g} |"
        )
    (output / "table_metrics.md").write_text("\n".join(lines) + "\n")
    return rows



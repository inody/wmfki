def production_report(output, requested, records, reference, application_summary, trajectory):
    comparison = read_json(output / "comparison_report.json")
    confirmation = None
    if requested.get("source_mode") != "fresh_full_pair_stage_outputs":
        confirmation = read_json(
            ROOT / requested["source_confirmation_run"] / "confirmation_report.json"
        )
    slopes = {method: sweep_slopes(records, method) for method in ("lasso", "ols")}
    full_slopes = {method: sweep_slopes(reference, method) for method in ("lasso", "ols")}
    condition_wins = 0
    for condition_id in sorted({row["condition"]["id"] for row in records}):
        selected = [row for row in records if row["condition"]["id"] == condition_id]
        lasso = np.mean([row["methods"]["lasso"]["held_out_drift"]["species_balanced_relative"] for row in selected])
        ols = np.mean([row["methods"]["ols"]["held_out_drift"]["species_balanced_relative"] for row in selected])
        condition_wins += int(lasso < ols)
    report = {
        "task": requested["task"],
        "study_status": requested["study_status"],
        "records": len(records),
        "full_pair_reference_records": len(reference),
        "comparison": comparison,
        "nominal_application": {
            "summary": application_summary,
            "trajectory": trajectory,
        },
        "sweep_slopes": {"P50": slopes, "full_pair": full_slopes},
        "lasso_better_than_ols_conditions": condition_wins,
        "condition_count": 13,
        "confirmation_source": (
            {
                "run": requested["source_confirmation_run"],
                "report_sha256": requested["source_confirmation_report_sha256"],
                "P50_claim_retention": confirmation["claim_retention"]["50"],
            }
            if confirmation is not None
            else {
                "status": "not_required",
                "reason": "fresh source-to-output reproduction runs P=50N directly",
            }
        ),
        "production_conclusion": (
            "P=50N preserves the matched-R20 qualitative drift, trajectory, sweep-direction, slope-sign, and LASSO-ranking claims; "
            "the carried strict relative profile gate remains failed, so this is a scientific candidate artifact rather than an automatic manuscript replacement."
        ),
    }
    write_json(output / "production_report.json", report)
    lines = [
        "# Predator--prey P=50N scientific candidate", "",
        report["production_conclusion"], "",
        f"Records: {len(records)}", "",
        f"LASSO better than OLS: {condition_wins}/13 conditions", "",
        "See table_metrics.md, nominal_application/, and figures/ for publication-preparation artifacts.",
    ]
    (output / "production_report.md").write_text("\n".join(lines) + "\n")
    return report


def exact_confirmation_parity(records, requested):
    if requested.get("source_mode") == "fresh_full_pair_stage_outputs":
        result = {
            "status": "not_required",
            "record_count": len(records),
            "expected_record_count": len(records),
            "exact_record_equality": None,
            "reason": "fresh source-to-output reproduction runs P=50N directly",
        }
        write_json(Path(requested["_output"]) / "confirmation_parity_report.json", result)
        return result
    source = read_json(ROOT / requested["source_confirmation_run"] / "records.json")
    source = [row for row in source if int(row["pair_ratio"]) == 50]
    key = lambda row: (int(row["repetition"]), row["condition"]["id"])
    source.sort(key=key)
    actual = sorted(records, key=key)
    result = {
        "status": "passed" if actual == source else "failed",
        "record_count": len(actual),
        "expected_record_count": len(source),
        "exact_record_equality": actual == source,
        "source_confirmation_records_sha256": requested["source_confirmation_records_sha256"],
    }
    write_json(Path(requested["_output"]) / "confirmation_parity_report.json", result)
    return result


def update_manifest(output, application_manifest, report, parity, copied):
    manifest = read_json(output / "manifest.json")
    extra = [
        "production_report.json", "production_report.md",
        "table_metrics.json", "table_metrics.csv", "table_metrics.md",
        "confirmation_parity_report.json",
    ]
    for name in extra:
        manifest.setdefault("artifact_sha256", {})[name] = digest(output / name)
    manifest["nominal_application_manifest_sha256"] = digest(output / "nominal_application" / "manifest.json")
    manifest["production_figure_sha256"] = {path.name: digest(path) for path in copied}
    manifest["confirmation_parity_status"] = parity["status"]
    manifest["lasso_better_than_ols_conditions"] = report["lasso_better_than_ols_conditions"]
    manifest["status"] = "scientific_candidate_complete"
    write_json(output / "manifest.json", manifest)
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=ROOT / CONFIG_RELATIVE)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--workers", type=int, default=5)
    args = parser.parse_args()
    if not 1 <= args.workers <= 5:
        parser.error("--workers must be between 1 and 5")
    requested = read_json(args.config)
    validate_production(requested)
    patch_runner()
    runner.run_study(requested, args.output, workers=args.workers)
    output = Path(args.output).resolve()
    requested["_output"] = str(output)
    records = read_json(output / "records.json")
    reference = read_json(output / "matched_full_pair_reference_R5.json")
    spec = read_json(output / "effective_protocol.json")
    application_summary, trajectory, application_manifest = create_application(
        output, requested, spec, records, reference
    )
    table_metrics(output, records, reference, application_summary, trajectory)
    copied = copy_production_figures(output)
    report = production_report(
        output, requested, records, reference, application_summary, trajectory
    )
    parity = exact_confirmation_parity(records, requested)
    manifest = update_manifest(output, application_manifest, report, parity, copied)
    print(json.dumps({
        "status": manifest["status"],
        "output": str(output),
        "confirmation_parity": parity["status"],
        "lasso_better_than_ols_conditions": report["lasso_better_than_ols_conditions"],
    }, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
